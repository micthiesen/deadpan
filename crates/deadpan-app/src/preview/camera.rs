    #[test]
    fn camera_adjusts_the_whole_curve_and_controls_without_changing_time_hosts() {
        let original = Framing::creep(
            pose(50, 100),
            pose(60, 135),
            FramingCurve::Cubic {
                control1: pose(45, 105),
                control2: pose(55, 120),
            },
        )
        .unwrap();
        let changed = adjusted_framing(Some(&original), pose(50, 100), pose(60, 200), false)
            .unwrap()
            .unwrap();
        let FramingValue::Envelope { envelope } = &changed.value else {
            panic!("curve collapsed")
        };
        assert_eq!(envelope.initial, pose(60, 200).quantized().unwrap());
        assert_eq!(envelope.segments[0].end, ExactRatio::ONE);
        assert_eq!(
            envelope.segments[0].pose,
            pose(70, 270).quantized().unwrap()
        );
        assert_eq!(
            envelope.segments[0].curve,
            FramingCurve::Cubic {
                control1: pose(55, 210).quantized().unwrap(),
                control2: pose(65, 240).quantized().unwrap(),
            }
        );
        assert_eq!(
            adjusted_framing(Some(&original), pose(50, 100), pose(50, 100), false).unwrap(),
            Some(original.clone())
        );
        assert_eq!(
            adjusted_framing(
                Some(&original),
                pose(50, 100),
                FramingPose::identity(),
                true
            )
            .unwrap(),
            None
        );
        let static_after_reset =
            adjusted_framing(Some(&original), pose(50, 100), pose(55, 150), true)
                .unwrap()
                .unwrap();
        assert_eq!(
            static_after_reset.value,
            FramingValue::Static {
                pose: pose(55, 150)
            }
        );
    }

