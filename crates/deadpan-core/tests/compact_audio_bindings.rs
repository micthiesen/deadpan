use deadpan_core::*;
use serde_json::{Value, json};

fn id(value: &str) -> NodeId {
    NodeId::new(value).unwrap()
}
fn revision(value: &str) -> RevisionId {
    RevisionId::new(value).unwrap()
}
fn exact(numerator: i128, denominator: i128) -> ExactRatio {
    ExactRatio::new(numerator, denominator).unwrap()
}
fn timing() -> AudioTimingId {
    AudioTimingId {
        allocation: revision("timing"),
        ordinal: 0,
    }
}
fn default_placement() -> AudioPlacementTemplate {
    AudioPlacementTemplate {
        reference: AudioReferenceClock {
            timing: timing(),
            root: AudioClockRoot::ProjectRootRoundEven,
            physical: id("owner"),
            recipe: AudioRecipeKind::Node,
        },
        reference_local_offset: ExactRatio::ZERO,
        gap_after: None,
        arguments: vec![],
        births: vec![],
    }
}
fn default_binding() -> OwnedAudioBinding {
    OwnedAudioBinding {
        lattice: default_placement(),
        resume: None,
        reanchors: vec![],
    }
}

// These expected bytes describe the intended compact wire directly. They are
// fixed contract literals, not output generated by the serializer under test.
const COMPACT_DEFAULT_BINDING: &str = r#"{"lattice":{"reference":{"timing":{"allocation":"timing","ordinal":0},"physical":"owner"}}}"#;
const HISTORICAL_EXPLICIT_DEFAULT_BINDING: &str = r#"{"lattice":{"reference":{"timing":{"allocation":"timing","ordinal":0},"root":{"type":"project_root_round_even"},"physical":"owner"},"arguments":[],"births":[]},"resume":null,"reanchors":[]}"#;
const COMPACT_ZERO_RESUME: &str = r#"{"lattice":{"reference":{"timing":{"allocation":"timing","ordinal":0},"physical":"owner"}},"resume":{"phase":{"terms":[]}}}"#;

#[test]
fn six_exact_binding_defaults_omit_and_restore_with_fixed_wire_bytes() {
    let binding = default_binding();
    assert_eq!(
        serde_json::to_string(&binding).unwrap(),
        COMPACT_DEFAULT_BINDING
    );
    let decoded: OwnedAudioBinding = serde_json::from_str(COMPACT_DEFAULT_BINDING).unwrap();
    assert_eq!(decoded, binding);

    let legacy: OwnedAudioBinding =
        serde_json::from_str(HISTORICAL_EXPLICIT_DEFAULT_BINDING).unwrap();
    assert_eq!(legacy, binding);
    assert_eq!(
        serde_json::to_string(&legacy).unwrap(),
        COMPACT_DEFAULT_BINDING
    );

    // A present resume keeps its shape, while its exact zero boundary and
    // phase constant independently use the same wire defaults.
    let zero_resume: OwnedAudioBinding = serde_json::from_str(COMPACT_ZERO_RESUME).unwrap();
    assert_eq!(
        zero_resume.resume,
        Some(AudioResume {
            local_boundary: ExactRatio::ZERO,
            phase: AudioLocalPhase::default(),
        })
    );
    assert_eq!(
        serde_json::to_string(&zero_resume).unwrap(),
        COMPACT_ZERO_RESUME
    );
}

#[test]
fn every_nondefault_clock_root_and_nonempty_lexical_path_roundtrips_exactly() {
    let roots = [
        AudioClockRoot::ProjectRootRoundEven,
        AudioClockRoot::PreserveInputPointCeil {
            stage: id("provider"),
        },
        AudioClockRoot::DefinitionPointCeil {
            root: id("definition"),
        },
        AudioClockRoot::GapDefinitionPointCeil {
            repeat: id("gap-repeat"),
        },
    ];
    let expected_roots = [
        json!({"type":"project_root_round_even"}),
        json!({"type":"preserve_input_point_ceil","stage":"provider"}),
        json!({"type":"definition_point_ceil","root":"definition"}),
        json!({"type":"gap_definition_point_ceil","repeat":"gap-repeat"}),
    ];
    for (root, expected) in roots.into_iter().zip(expected_roots) {
        let clock = AudioReferenceClock {
            timing: timing(),
            root: root.clone(),
            physical: id("owner"),
            recipe: AudioRecipeKind::Node,
        };
        let encoded = serde_json::to_value(&clock).unwrap();
        if root == AudioClockRoot::ProjectRootRoundEven {
            assert!(encoded.get("root").is_none());
        } else {
            assert_eq!(encoded["root"], expected);
        }
        assert_eq!(
            serde_json::from_value::<AudioReferenceClock>(encoded).unwrap(),
            clock
        );
    }

    let mut placement = default_placement();
    placement.reference.root = AudioClockRoot::PreserveInputPointCeil { stage: id("outer") };
    placement.arguments = vec![
        AudioRepeatArgument {
            reference_repeat: id("outer"),
            value: AudioRepeatValue::Live {
                repeat: id("outer"),
            },
        },
        AudioRepeatArgument {
            reference_repeat: id("inner"),
            value: AudioRepeatValue::Captured {
                iteration: IterationId {
                    allocation: revision("plays"),
                    ordinal: 7,
                },
            },
        },
    ];
    placement.births = vec![AudioBirthClause {
        repeat: id("outer"),
        survivors: AudioBirthSurvivors::Run {
            allocation: revision("births"),
            first: 3,
            count: 5,
        },
        definition_root: id("definition"),
    }];
    let wire = serde_json::to_value(&placement).unwrap();
    assert_eq!(
        wire["arguments"],
        json!([
            {"reference_repeat":"outer","value":{"type":"live","repeat":"outer"}},
            {"reference_repeat":"inner","value":{"type":"captured","iteration":{"allocation":"plays","ordinal":7}}}
        ])
    );
    assert_eq!(
        wire["births"],
        json!([
            {"repeat":"outer","survivors":{"type":"run","allocation":"births","first":3,"count":5},"definition_root":"definition"}
        ])
    );
    assert_eq!(
        serde_json::from_value::<AudioPlacementTemplate>(wire).unwrap(),
        placement
    );
}

#[test]
fn signed_nonzero_resume_values_and_phase_terms_remain_explicit_and_exact() {
    let mut placement = default_placement();
    placement.reference.root = AudioClockRoot::DefinitionPointCeil { root: id("def") };
    placement.arguments.push(AudioRepeatArgument {
        reference_repeat: id("repeat"),
        value: AudioRepeatValue::Live {
            repeat: id("repeat"),
        },
    });
    let resume = AudioResume {
        local_boundary: exact(7, 11),
        phase: AudioLocalPhase {
            constant: exact(-5, 13),
            terms: vec![AudioPhaseTerm {
                placement: placement.clone(),
                from_local: exact(-2, 7),
                to_local: exact(9, 14),
            }],
        },
    };
    let binding = OwnedAudioBinding {
        resume: Some(resume.clone()),
        ..default_binding()
    };
    let wire = serde_json::to_value(&binding).unwrap();
    assert_eq!(
        wire["resume"]["local_boundary"],
        json!({"numerator":"7","denominator":"11"})
    );
    assert_eq!(
        wire["resume"]["phase"]["constant"],
        json!({"numerator":"-5","denominator":"13"})
    );
    assert_eq!(
        wire["resume"]["phase"]["terms"][0]["from_local"],
        json!({"numerator":"-2","denominator":"7"})
    );
    assert_eq!(
        wire["resume"]["phase"]["terms"][0]["to_local"],
        json!({"numerator":"9","denominator":"14"})
    );
    assert!(wire["resume"].get("local_boundary").is_some());
    assert!(wire["resume"]["phase"].get("constant").is_some());
    assert_eq!(
        serde_json::from_value::<OwnedAudioBinding>(wire).unwrap(),
        binding
    );
}

#[test]
fn malformed_unknown_duplicate_and_null_nonoptional_fields_are_rejected() {
    let malformed = [
        r#"{"lattice":{"reference":{"timing":{"allocation":"timing","ordinal":0},"physical":"owner"},"arguments":null,"births":[]}}"#,
        r#"{"lattice":{"reference":{"timing":{"allocation":"timing","ordinal":0},"physical":"owner"},"arguments":[],"births":null}}"#,
        r#"{"lattice":{"reference":{"timing":{"allocation":"timing","ordinal":0},"physical":"owner"},"births":[],"unexpected":true}}"#,
        r#"{"lattice":{"reference":{"timing":{"allocation":"timing","ordinal":0},"physical":"owner","root":null},"arguments":[],"births":[]}}"#,
        r#"{"lattice":{"reference":{"timing":{"allocation":"timing","ordinal":0},"physical":"owner"},"arguments":[],"arguments":[],"births":[]}}"#,
        r#"{"lattice":{"reference":{"timing":{"allocation":"timing","ordinal":0},"physical":"owner"},"arguments":[],"births":[]},"resume":{"local_boundary":null,"phase":{"constant":{"numerator":"0","denominator":"1"},"terms":[]}}}"#,
        r#"{"lattice":{"reference":{"timing":{"allocation":"timing","ordinal":0},"physical":"owner"},"arguments":[],"births":[]},"resume":{"local_boundary":{"numerator":"0","denominator":"1"},"phase":{"constant":null,"terms":[]}}}"#,
    ];
    for raw in malformed {
        assert!(
            serde_json::from_str::<OwnedAudioBinding>(raw).is_err(),
            "accepted {raw}"
        );
    }
    // `resume` is an Option and explicit null remains its valid historical form.
    let mut null_resume =
        serde_json::from_str::<Value>(HISTORICAL_EXPLICIT_DEFAULT_BINDING).unwrap();
    null_resume["resume"] = Value::Null;
    assert!(serde_json::from_value::<OwnedAudioBinding>(null_resume).is_ok());
}

#[test]
fn present_argument_and_birth_vectors_keep_their_existing_admission_bound() {
    let argument = json!({
        "reference_repeat":"repeat",
        "value":{"type":"live","repeat":"repeat"}
    });
    let oversized = json!({
        "lattice":{
            "reference":{"timing":{"allocation":"timing","ordinal":0},"physical":"owner"},
            "arguments":vec![argument; MAX_DOCUMENT_DEPTH + 1],
            "births":[]
        }
    });
    assert!(serde_json::from_value::<OwnedAudioBinding>(oversized).is_err());

    let birth = json!({
        "repeat":"repeat",
        "survivors":{"type":"run","allocation":"births","first":0,"count":1},
        "definition_root":"definition"
    });
    let oversized = json!({
        "lattice":{
            "reference":{"timing":{"allocation":"timing","ordinal":0},"physical":"owner"},
            "arguments":[],
            "births":vec![birth; MAX_DOCUMENT_DEPTH + 1]
        }
    });
    assert!(serde_json::from_value::<OwnedAudioBinding>(oversized).is_err());
}

fn nested_state() -> AudioBindingState {
    let document = document_with_hold();
    let template = default_placement();
    let binding = OwnedAudioBinding {
        lattice: template.clone(),
        resume: Some(AudioResume {
            local_boundary: ExactRatio::ONE,
            phase: AudioLocalPhase {
                constant: ExactRatio::ZERO,
                terms: vec![AudioPhaseTerm {
                    placement: template.clone(),
                    from_local: ExactRatio::ZERO,
                    to_local: ExactRatio::ONE,
                }],
            },
        }),
        reanchors: vec![AudioReanchorStep {
            placement: template,
            window: None,
            anchor: AudioReanchorAnchor::AllocationEntry,
        }],
    };
    let state = AudioBindingState::new(
        vec![AudioTimingRecord {
            id: timing(),
            layout: FrozenAudioLayout::capture(&document).unwrap(),
        }],
        vec![(id("owner"), binding)].into_iter().collect(),
    )
    .unwrap();
    state.validate_for(&document).unwrap();
    state
}

#[test]
fn audio_binding_state_preflight_accepts_absent_and_explicit_path_defaults_at_every_placement() {
    let state = nested_state();
    let mut explicit_value: Value = serde_json::from_str(&state.to_json().unwrap()).unwrap();
    let absent_value = explicit_value.clone();
    fn set_paths(template: &mut Value, explicit: bool) {
        if explicit {
            template["arguments"] = json!([]);
            template["births"] = json!([]);
        } else if let Some(object) = template.as_object_mut() {
            object.remove("arguments");
            object.remove("births");
        }
    }
    let owner = &mut explicit_value["bindings"]["owner"];
    set_paths(&mut owner["lattice"], true);
    set_paths(&mut owner["resume"]["phase"]["terms"][0]["placement"], true);
    set_paths(&mut owner["reanchors"][0]["placement"], true);
    let mut absent_value = absent_value;
    let owner = &mut absent_value["bindings"]["owner"];
    set_paths(&mut owner["lattice"], false);
    set_paths(
        &mut owner["resume"]["phase"]["terms"][0]["placement"],
        false,
    );
    set_paths(&mut owner["reanchors"][0]["placement"], false);
    let absent_state = AudioBindingState::from_json(&absent_value.to_string()).unwrap();
    let explicit_state = AudioBindingState::from_json(&explicit_value.to_string()).unwrap();
    assert_eq!(absent_state, state);
    assert_eq!(explicit_state, state);
    let compact: Value = serde_json::from_str(&absent_state.to_json().unwrap()).unwrap();
    assert!(
        compact["bindings"]["owner"]["lattice"]
            .get("arguments")
            .is_none()
    );
    assert!(
        compact["bindings"]["owner"]["lattice"]
            .get("births")
            .is_none()
    );

    let nested_state = explicit_state;
    let owner = &nested_state.bindings()[&id("owner")];
    assert!(owner.lattice.arguments.is_empty() && owner.lattice.births.is_empty());
    let resume = owner.resume.as_ref().unwrap();
    assert!(resume.phase.terms[0].placement.arguments.is_empty());
    assert!(resume.phase.terms[0].placement.births.is_empty());
    assert!(owner.reanchors[0].placement.arguments.is_empty());
    assert!(owner.reanchors[0].placement.births.is_empty());
}

#[test]
fn audio_binding_state_preflight_rejects_null_duplicate_and_oversized_paths() {
    let state = nested_state();
    let base: Value = serde_json::from_str(&state.to_json().unwrap()).unwrap();

    assert_eq!(
        AudioBindingState::from_json(&base.to_string()).unwrap(),
        state
    );
    let placements = [
        "/bindings/owner/lattice",
        "/bindings/owner/resume/phase/terms/0/placement",
        "/bindings/owner/reanchors/0/placement",
    ];
    for placement in placements {
        for path in ["arguments", "births"] {
            let mut null = base.clone();
            null.pointer_mut(placement).unwrap()[path] = Value::Null;
            assert!(
                AudioBindingState::from_json(&null.to_string()).is_err(),
                "accepted null {placement}/{path}"
            );
            // Deliberately opaque entries prove the bounded raw pass rejects
            // the collection before interpreting its members.
            let mut oversized = base.clone();
            oversized.pointer_mut(placement).unwrap()[path] =
                json!(vec![Value::Null; MAX_DOCUMENT_DEPTH + 1]);
            let error = AudioBindingState::from_json(&oversized.to_string()).unwrap_err();
            assert!(
                error.message.contains("audio binding sequence limit"),
                "wrong refusal for {placement}/{path}: {error:?}"
            );
        }
    }
    let compact = state.to_json().unwrap();
    // Exercise the raw-JSON preflight in each nested template location too.
    // The compact serialization has three identical reference fragments, in
    // lattice, resume term, and reanchor order.
    let marker = "\"physical\":\"owner\"}}";
    let insertion = "\"physical\":\"owner\"},\"arguments\":[],\"arguments\":[],\"births\":[]}";
    let mut from = 0;
    let mut duplicate_locations = 0;
    while let Some(relative) = compact[from..].find(marker) {
        let at = from + relative;
        let malformed = format!(
            "{}{}{}",
            &compact[..at],
            insertion,
            &compact[at + marker.len()..]
        );
        assert!(AudioBindingState::from_json(&malformed).is_err());
        duplicate_locations += 1;
        from = at + marker.len();
    }
    assert_eq!(
        duplicate_locations, 3,
        "expected lattice, phase-term, and reanchor templates"
    );
}

fn hold(frames: i64) -> BeatNode {
    BeatNode::hold(
        "Hold",
        HoldRecipe {
            picture_context: None,
            duration: FrameDuration::new(frames).unwrap(),
            video: HoldVideo::Background,
            audio: HoldAudio::Silence,
        },
    )
}
fn document_with_hold() -> ProjectDocument {
    let base = ProjectDocument::new(
        ProjectId::new("binding-history").unwrap(),
        revision("initial"),
        PresentationBasis {
            width: 16,
            height: 16,
            frame_rate: FrameRate::new(30, 1).unwrap(),
            color_policy: ColorPolicy::SdrRec709,
        },
        id("root"),
    )
    .unwrap();
    let mut wire = serde_json::to_value(base).unwrap();
    wire["nodes"]["owner"] = serde_json::to_value(hold(4)).unwrap();
    wire["nodes"]["root"] =
        serde_json::to_value(BeatNode::sequence("Root", vec![id("owner")])).unwrap();
    ProjectDocument::from_json(&wire.to_string()).unwrap()
}

#[test]
fn captured_binding_state_and_insert_history_patch_roundtrip_compact_wire() {
    let unbound = document_with_hold();
    let captured = capture_unbound_audio_bindings(
        &unbound,
        AudioTimingId {
            allocation: revision("capture"),
            ordinal: 0,
        },
    )
    .unwrap();
    let captured_wire = captured.to_json().unwrap();
    let captured_again = AudioBindingState::from_json(&captured_wire).unwrap();
    assert_eq!(captured_again, captured);

    let mut document_wire = serde_json::to_value(unbound).unwrap();
    document_wire["audio_bindings"] = serde_json::from_str(&captured_wire).unwrap();
    let bound = ProjectDocument::from_json(&document_wire.to_string()).unwrap();
    let request = CommandRequest {
        project_id: bound.project_id().clone(),
        expected_revision: bound.revision_id().clone(),
        new_revision: revision("pause"),
        command: Command::InsertTime {
            at: ProjectFrame(1),
            hold: HoldRecipe {
                picture_context: None,
                duration: FrameDuration::new(1).unwrap(),
                video: HoldVideo::Background,
                audio: HoldAudio::Silence,
            },
            id: id("pause-node"),
            identities: SplitIdentities {
                nodes: (0..3).map(|n| id(&format!("split-{n}"))).collect(),
            },
            timing: AudioTimingId {
                allocation: revision("pause"),
                ordinal: 0,
            },
        },
    };
    let transaction = apply(&bound, &request).unwrap();
    assert!(transaction.forward.audio_bindings.is_some());
    let history_json = serde_json::to_string(&transaction.forward).unwrap();
    let decoded: DocumentPatch = serde_json::from_str(&history_json).unwrap();
    assert_eq!(decoded, transaction.forward);
    let after = decoded.apply(&bound).unwrap();
    assert_eq!(decoded.inverse().apply(&after).unwrap(), bound);
    assert_eq!(
        AudioBindingState::from_json(&after.audio_bindings().to_json().unwrap()).unwrap(),
        *after.audio_bindings()
    );
}
