"""Original non-face proposal fixtures; no external media or detector output.

Swift/CoreGraphics draws blank, blue mug and mug+orange source rasters.
The development FFmpeg CLI converts declared full-range BGRA to BT.709
limited-range yuv420p. FFV1 encodes those YUV pictures losslessly. Main and
4:3 SAR fixtures contain 120 video-only pictures at nominal 30000/1001.
An additional H264 MP4 retains the exact CFR clock (1001 ticks per picture
at timebase 1/30000) for default Original cadence admission. A separate WAV
retains the original 192192 stereo PCM16 samples at 48 kHz. Matroska uses its
measured millisecond PTS; those inputs retain explicit-profile qualification.

Short lossless-H264 geometry fixtures keep four mug pictures, with a CW90
display matrix or an exact fractional clean aperture. Tests decode all
fixtures only with the separately selected qualified product libraries.
--check compares regenerated bytes; --work-dir retains exact raw inputs,
argv and tool output for qualification. This generator runs no Vision.
"""
import argparse
import hashlib
import importlib.util
import json
import math
from pathlib import Path
import struct
import subprocess
import sys
import tempfile
import wave

ROOT = Path(__file__).parent
FIXTURES = ROOT / "fixtures"
W, H, FRAMES, SAMPLES = 640, 360, 120, 192192
COLOR = ["-color_range", "tv", "-colorspace", "bt709", "-color_trc", "bt709",
         "-color_primaries", "bt709", "-chroma_sample_location", "left"]
FILTER = ("scale=in_range=pc:out_range=tv:out_color_matrix=bt709,format=yuv420p,"
          "setparams=range=tv:color_primaries=bt709:color_trc=bt709:colorspace=bt709")
COMMON = ["-nostdin", "-v", "error", "-fflags", "+bitexact"]


def digest(data):
    return hashlib.sha256(data).hexdigest()


def generate(work, check):
    calls = []
    def run(argv, binary=False):
        result = subprocess.run(argv, check=False, capture_output=True)
        calls.append({"argv": [str(arg) for arg in argv], "returncode": result.returncode,
                      "stderr": result.stderr.decode(errors="replace")})
        (work / "exact-argv-and-stderr.json").write_text(json.dumps(calls, indent=2) + "\n")
        result.check_returncode()
        return result.stdout if binary else result.stdout.decode()

    images = work / "images"
    run(["swift", "-module-cache-path", str(work / "swift-module-cache"),
         str(ROOT / "generate_salient_images.swift"), str(images)])
    image_metadata = json.loads((images / "images.json").read_text())
    rasters = [(images / (name + ".bgra")).read_bytes()
               for name in ["salient-blank", "salient-mug", "salient-two"]]
    assert all(len(frame) == W * H * 4 for frame in rasters)
    raw = work / "frames.bgra"
    raw.write_bytes(b"".join(rasters[min(frame // 40, 2)] for frame in range(FRAMES)))
    pcm = bytearray()
    for sample in range(SAMPLES):
        # An original deterministic low-level tone plus short exact pulse.
        value = round(2200 * math.sin(2 * math.pi * 440 * sample / 48000))
        if 48000 <= sample < 48032:
            value += 6000
        pcm.extend(struct.pack("<hh", value, -value))
    audio = work / "audio.s16le"
    audio.write_bytes(pcm)
    version = run(["ffmpeg", "-version"])
    license_text = run(["ffmpeg", "-L"])
    probe_version = run(["ffprobe", "-version"])
    out = work / "encoded"
    out.mkdir()
    for name, sar in [("salient-regions.mkv", "1/1"), ("salient-regions-sar.mkv", "4/3")]:
        run(["ffmpeg", *COMMON, "-f", "rawvideo", "-pixel_format", "bgra",
             "-video_size", f"{W}x{H}", "-framerate", "30000/1001", "-i", str(raw),
             "-map", "0:v:0", "-an", "-vf", FILTER + ",setsar=" + sar,
             "-c:v", "ffv1", "-level", "3", "-pix_fmt", "yuv420p",
             "-flags:v", "+bitexact", *COLOR, "-fflags", "+bitexact",
             "-y", str(out / name)])
    run(["ffmpeg", *COMMON, "-f", "rawvideo", "-pixel_format", "bgra",
         "-video_size", f"{W}x{H}", "-framerate", "30000/1001", "-i", str(raw),
         "-map", "0:v:0", "-an", "-vf", FILTER,
         "-c:v", "libx264", "-qp", "0", "-threads:v", "1",
         "-x264-params", "keyint=1:scenecut=0:colorprim=bt709:transfer=bt709:colormatrix=bt709",
         "-pix_fmt", "yuv420p", "-flags:v", "+bitexact", *COLOR,
         "-fps_mode", "cfr", "-video_track_timescale", "30000",
         "-movflags", "+faststart", "-fflags", "+bitexact",
         "-y", str(out / "salient-regions.mp4")])
    mug_raw = work / "mug-four.bgra"
    mug_raw.write_bytes(rasters[1] * 4)
    coded = work / "mug-coded.mp4"
    run(["ffmpeg", *COMMON, "-f", "rawvideo", "-pixel_format", "bgra",
         "-video_size", f"{W}x{H}", "-framerate", "30000/1001", "-i", str(mug_raw),
         "-vf", FILTER, "-an", "-c:v", "libx264", "-qp", "0",
         "-x264-params", "keyint=1:scenecut=0:colorprim=bt709:transfer=bt709:colormatrix=bt709",
         "-pix_fmt", "yuv420p", "-flags:v", "+bitexact", *COLOR,
         "-movflags", "+faststart", "-y", str(coded)])
    run(["ffmpeg", *COMMON, "-display_rotation", "-90", "-i", str(coded), "-c", "copy",
         "-movflags", "+faststart", "-y", str(out / "salient-mug-rotated-90.mp4")])
    # Use the project's independently checked MP4 atom transformer. Only clap,
    # enclosing sizes and chunk offsets change; compressed bytes/PTS stay exact.
    sys.dont_write_bytecode = True
    spec = importlib.util.spec_from_file_location(
        "deadpan_aperture", ROOT / "../../deadpan-source/tests/generate_aperture_fixtures.py")
    aperture = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(aperture)
    words = [959, 2, 639, 2, 80, 1, 0, 1]
    (out / "salient-mug-aperture.mp4").write_bytes(aperture.generate(coded.read_bytes(), words))

    properties = {}
    for path in sorted(out.iterdir()):
        probe = json.loads(run(["ffprobe", "-v", "error", "-show_streams", "-show_format",
                                "-show_frames", "-of", "json", str(path)]))
        video = next(stream for stream in probe["streams"] if stream["codec_type"] == "video")
        frames = [frame for frame in probe["frames"] if frame["media_type"] == "video"]
        row = {"bytes": path.stat().st_size, "sha256": digest(path.read_bytes()),
               "video": {key: video.get(key) for key in
                         ["codec_name", "profile", "width", "height", "pix_fmt", "sample_aspect_ratio",
                          "r_frame_rate", "avg_frame_rate", "time_base", "color_range", "color_space",
                          "color_transfer", "color_primaries", "duration_ts", "side_data_list"]},
               "frames": [{"pts": frame["pts"], "duration": frame.get("duration")}
                          for frame in frames],
               "format_duration": probe["format"].get("duration")}
        assert len(frames) == (FRAMES if path.name.startswith("salient-regions") else 4)
        if path.name == "salient-regions.mp4":
            assert video["time_base"] == "1/30000"
            assert video["duration_ts"] == 120120
            assert all(frame["pts"] == 1001 * index and frame["duration"] == 1001
                       for index, frame in enumerate(frames))
            assert not any(stream["codec_type"] == "audio" for stream in probe["streams"])
        properties[path.name] = row
    manifest = {"producer": version, "producer_license": license_text, "ffprobe": probe_version,
                "original_artwork": "CoreGraphics generator, MIT; no external or person footage",
                "sections": [{"start": 0, "end": 40, "image": "blank"},
                             {"start": 40, "end": 80, "image": "mug"},
                             {"start": 80, "end": 120, "image": "mug_and_orange"}],
                "source_images": image_metadata, "raw_bgra_sha256": digest(raw.read_bytes()),
                "raw_pcm_s16le_sha256": digest(bytes(pcm)), "fixtures": properties,
                "fractional_aperture": {"clap_words": words, "left": "641/4", "top": "81/4",
                                       "width": "959/2", "height": "639/2"},
                "limits": "Producer metadata only; qualified product decoder and Vision tests remain required"}
    wav = work / "salient-audio.wav"
    with wave.open(str(wav), "wb") as stream:
        stream.setnchannels(2)
        stream.setsampwidth(2)
        stream.setframerate(48000)
        stream.writeframes(pcm)
    manifest["audio_fixture"] = {"name": wav.name, "bytes": wav.stat().st_size,
                                 "sha256": digest(wav.read_bytes()), "samples": SAMPLES,
                                 "rate": 48000, "channels": 2, "encoding": "PCM16LE"}
    outputs = {path.name: path.read_bytes() for path in out.iterdir()}
    outputs[wav.name] = wav.read_bytes()
    outputs.update({name + ".png": (images / (name + ".png")).read_bytes()
                    for name in ["salient-blank", "salient-mug", "salient-two"]})
    outputs["salient-regions-fixtures.json"] = (json.dumps(manifest, indent=2, sort_keys=True) + "\n").encode()
    for name, data in outputs.items():
        target = FIXTURES / name
        if check:
            assert target.read_bytes() == data, f"fixture differs: {name}"
        else:
            if not target.exists() or target.read_bytes() != data:
                target.write_bytes(data)
        print(json.dumps({"name": name, "bytes": len(data), "sha256": digest(data)}))
    (work / "exact-argv-and-stderr.json").write_text(json.dumps(calls, indent=2) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--work-dir", type=Path)
    args = parser.parse_args()
    if args.work_dir:
        args.work_dir.mkdir(parents=True, exist_ok=False)
        generate(args.work_dir, args.check)
    else:
        with tempfile.TemporaryDirectory(prefix="deadpan-salient-fixtures-") as directory:
            generate(Path(directory), args.check)


if __name__ == "__main__":
    main()
